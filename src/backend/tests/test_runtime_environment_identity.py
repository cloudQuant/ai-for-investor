def _venv(venv_root: Path, site_packages: Path, **overrides: Any) -> checker.VenvIsolation:
    """Build isolation evidence directly, so tests never depend on the runner's own venv."""
    values: dict[str, Any] = {
        "running_in_venv": True,
        "prefix": str(venv_root),
        "base_prefix": str(venv_root.parent / "usr"),
        "pyvenv_cfg_path": str(venv_root / "pyvenv.cfg"),
        "include_system_site_packages": False,
        "creating_command": "/usr/bin/python3.11 -m venv /srv/venv",
        "base_home": "/usr/bin",
        "recorded_version": "3.11.9",
        "own_site_packages": str(site_packages),
        "distribution_count": 3,
    }
    values.update(overrides)
    return checker.VenvIsolation(**values)


def _lock_text(**pins: str) -> str:
    lines = ["# This file was autogenerated by uv via the following command:"]
    lines += [
        f"{name}=={version}    # via ai-for-investor-backend (pyproject.toml)"
        for name, version in pins.items()
    ]
    return "\n".join(lines) + "\n"


def _akshare_tables(
    specifier: str = AKSHARE_CONSTRAINT, *, marker: str | None = None
) -> dict[str, Any]:
    """A tomllib-shaped pyproject table carrying one declared akshare constraint."""
    requirement = f"akshare{specifier}" + (f"; {marker}" if marker else "")
    return {
        "project": {
            "dependencies": [],
            "optional-dependencies": {"data": [requirement], "backtrader": []},
        }
    }


def _akshare_module(site_packages: Path, version: str = "1.18.97") -> ModuleType:
    return SimpleNamespace(
        __version__=version, __file__=str(site_packages / "akshare" / "__init__.py")
    )


def _probe(
    *,
    venv: checker.VenvIsolation,
    module: Any | None = None,
    lock_text: str,
    tables: dict[str, Any],
    distribution: str = "akshare",
    importer: Any = None,
    python_version: str = "3.11",
) -> checker.DependencyObservation:
    if importer is None:
        captured = module

        def importer(_name: str) -> Any:
            return captured

    return checker.probe_dependency(
        distribution,
        lock=checker.parse_lock(lock_text),
        requirements=checker.parse_pyproject_requirements(tables),
        venv=venv,
        importer=importer,
        python_version=python_version,
    )


def _verdict(
    observations: list[checker.DependencyObservation],
    venv: checker.VenvIsolation,
    *,
    running_version: str = "3.11.9",
    matrix: tuple[str, ...] = ("3.11", "3.12"),
    expected_tz: str | None = "Asia/Shanghai",
    tz_value: str | None = "Asia/Shanghai",
    unreadable: tuple[str, ...] = (),
) -> checker.EnvironmentVerdict:
    return checker.build_verdict(
        interpreter=checker.check_interpreter(python_version=running_version, matrix=matrix),
        venv_check=checker.check_venv(venv),
        timezone_check=checker.check_timezone(
            expected_tz=expected_tz,
            observed={"tz_environment_value": tz_value, "utc_offset_seconds": 28800},
        ),
        observations=observations,
        unreadable_sources=unreadable,
    )


