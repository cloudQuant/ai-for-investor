    matching = checker.check_timezone(
        expected_tz="Asia/Shanghai", observed={"tz_environment_value": "Asia/Shanghai"}
    )

    assert mismatched["reasons"] == [checker.REASON_TIMEZONE_MISMATCH]
    assert posix["reasons"] == []
    assert posix["observed"]["name_comparable"] is False
    assert matching["reasons"] == []


