    assert entry["distribution"] == "akshare"
    assert entry["expected"]["lock_pin"] == "1.18.97"
    assert entry["observed"]["imported_version"] == "1.18.64"
    assert checker.REASON_VERSION_OUTSIDE_CONSTRAINT in entry["reasons"]
    assert SECRET_SENTINEL not in captured.out + captured.err


