def test_lock_parses_and_the_akshare_pin_is_found() -> None:
    pins = checker.parse_lock(_lock_text(**{"akshare": "1.18.97", "PyYAML": "6.0.3"}))

    assert pins["akshare"].version == "1.18.97"
    assert pins["akshare"].direct_url is None
    assert pins["pyyaml"].version == "6.0.3"  # PEP 503 normalized lookup key
    assert pins["akshare"].distribution in json.dumps(sorted(pins))


