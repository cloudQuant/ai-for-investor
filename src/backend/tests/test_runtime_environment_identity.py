"""Fixture-driven tests for the runtime environment identity checker.

No network, no database, no application imports: every case fabricates a lock, a pyproject
table, a CI workflow and a throwaway virtual environment under ``tmp_path``, then drives the
guard's own parsing and comparison functions with those inputs.  Each refusal is paired with
the counterfactual that accepts it, so loosening a check (trusting an unpinned import, skipping
the venv-membership test, echoing an environment value) makes at least one test fail.
"""

