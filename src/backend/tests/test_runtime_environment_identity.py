def test_main_prints_one_sanitized_json_payload_and_its_exit_code_matches(
    fabricated_sources: dict[str, str],
    site_packages: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    monkeypatch.setattr(
        checker,
        "_default_importer",
        lambda name: SimpleNamespace(
            __version__="1.18.64", __file__=str(site_packages / "akshare" / "__init__.py")
        ),
    )
    monkeypatch.setattr(checker.sys, "version", "3.13.5 | packaged by Anaconda, Inc.")

