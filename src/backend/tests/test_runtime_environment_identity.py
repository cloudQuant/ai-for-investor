def test_declared_constraint_is_parsed_from_the_requirement_table() -> None:
    requirements = checker.parse_pyproject_requirements(_akshare_tables())
    applicable = checker.applicable_requirement(requirements, "akshare", python_version="3.11")

    assert applicable is not None
    assert applicable.specifier == AKSHARE_CONSTRAINT
    assert checker.parse_pyproject_requirements({}) == {}


def test_environment_marker_siblings_select_the_constraint_for_this_interpreter() -> None:
    tables = {
        "project": {
            "dependencies": [],
            "optional-dependencies": {
                "data": [
                    "akshare>=1.18.96,<1.19; python_version >= '3.11'",
                    "akshare>=1.18.88,<1.18.89; python_version < '3.11'",
                ],
                "backtrader": [],
            },
        }
    }
    requirements = checker.parse_pyproject_requirements(tables)

    newer = checker.applicable_requirement(requirements, "akshare", python_version="3.12")
    older = checker.applicable_requirement(requirements, "akshare", python_version="3.10")

    assert newer is not None and newer.specifier == ">=1.18.96,<1.19"
    assert older is not None and older.specifier == ">=1.18.88,<1.18.89"
    assert not checker.marker_matches("python_version < '3.11'", python_version="3.12")


