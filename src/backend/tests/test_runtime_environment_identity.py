    assert observation.expected["pyproject_constraint"] == AKSHARE_CONSTRAINT
    assert observation.observed["imported_version"] == "1.18.64"
    # The counterfactual: the same probe with the pinned version refuses nothing.
    assert (
        _probe(
            venv=_venv(venv_root, site_packages),
            module=_akshare_module(site_packages, "1.18.97"),
            lock_text=_lock_text(**{"akshare": "1.18.97"}),
            tables=_akshare_tables(),
        ).reasons
        == []
    )


